"use client";

import { useId, useState } from "react";
import { ChevronDown, RotateCw } from "lucide-react";
import { Button } from "@/components/shared/Button";
import { FieldError } from "@/components/shared/FieldError";
import { usePointsOfPerformance } from "@/hooks/usePointsOfPerformance";
import { cn } from "@/utils/cn";

/** Collapsible points of performance for one movement, loaded the first time it's opened. */
export function PointsOfPerformance({ name }: { name: string }) {
  const [open, setOpen] = useState(false);
  const panelId = useId();
  const points = usePointsOfPerformance(name);

  function toggle() {
    if (!open) void points.load();
    setOpen(!open);
  }

  return (
    <div className="mt-3 border-t border-zinc-100 pt-2 dark:border-zinc-800">
      <Button
        variant="secondary"
        size="xs"
        onClick={toggle}
        aria-expanded={open}
        aria-controls={panelId}
        className="-ml-2"
      >
        <ChevronDown
          size={14}
          aria-hidden
          className={cn("transition-transform", open && "rotate-180")}
        />
        Points of performance
      </Button>

      <div id={panelId} hidden={!open} className="mt-2 text-sm">
        {points.status === "loading" && (
          <p role="status" className="text-zinc-500">
            Loading points of performance…
          </p>
        )}

        {points.status === "error" && (
          <div className="flex items-center gap-2">
            <FieldError role="alert">{points.error}</FieldError>
            <Button variant="secondary" size="xs" icon={RotateCw} onClick={() => points.load()}>
              Retry
            </Button>
          </div>
        )}

        {points.status === "success" && (
          <>
            <ol className="list-decimal space-y-1 pl-5 text-zinc-700 dark:text-zinc-300">
              {points.points.cues.map((cue) => (
                <li key={cue}>{cue}</li>
              ))}
            </ol>

            {points.points.faults.length > 0 && (
              <>
                <h4 className="mt-3 font-medium">Common faults</h4>
                <ul className="mt-1 space-y-1 text-zinc-600 dark:text-zinc-400">
                  {points.points.faults.map(({ fault, fix }) => (
                    <li key={fault}>
                      {fault} → <span className="text-zinc-800 dark:text-zinc-200">{fix}</span>
                    </li>
                  ))}
                </ul>
              </>
            )}

            {points.source === "ai" && (
              <p className="mt-3 text-xs text-zinc-500">
                Generated by AI. Double-check before coaching.
              </p>
            )}
          </>
        )}
      </div>
    </div>
  );
}
