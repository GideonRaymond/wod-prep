// @vitest-environment jsdom
import { cleanup, render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { PointsOfPerformance } from "./PointsOfPerformance";

const fetchMock = vi.fn();
const points = {
  cues: ["Front rack with elbows high", "Hips open, then press"],
  faults: [
    { fault: "Pressing early", fix: "Finish the hip drive first", cue: "Hips, then press!" },
  ],
};

function respond(status: number, body: unknown) {
  fetchMock.mockResolvedValue({ ok: status < 400, json: async () => body });
}

const toggle = () => screen.getByRole("button", { name: "Points of performance" });

function setup() {
  render(<PointsOfPerformance name="Thruster" />);
  return userEvent.setup();
}

describe("PointsOfPerformance", () => {
  beforeEach(() => {
    fetchMock.mockReset();
    vi.stubGlobal("fetch", fetchMock);
  });
  afterEach(() => {
    cleanup();
    vi.unstubAllGlobals();
  });

  it("starts collapsed and doesn't load anything", () => {
    setup();
    expect(toggle()).toHaveAttribute("aria-expanded", "false");
    expect(fetchMock).not.toHaveBeenCalled();
  });

  it("loads and shows the cues and faults when opened", async () => {
    respond(200, { points, source: "curated" });
    const user = setup();
    await user.click(toggle());

    expect(toggle()).toHaveAttribute("aria-expanded", "true");
    expect(JSON.parse(fetchMock.mock.calls[0][1].body)).toEqual({ name: "Thruster" });
    expect(await screen.findByText("Front rack with elbows high")).toBeVisible();
    expect(screen.getByText("Hips open, then press")).toBeInTheDocument();
    expect(screen.getByRole("heading", { name: "Common faults" })).toBeInTheDocument();
    expect(screen.getByText("Pressing early")).toBeInTheDocument();
    expect(screen.getByText("Finish the hip drive first")).toBeInTheDocument();
    expect(screen.getByTitle("Coaching cue")).toHaveTextContent("“Hips, then press!”");
    expect(screen.queryByText(/Generated by AI/)).not.toBeInTheDocument();
  });

  it("shows a loading message", async () => {
    fetchMock.mockReturnValue(new Promise(() => {}));
    const user = setup();
    await user.click(toggle());
    expect(screen.getByRole("status")).toHaveTextContent("Loading points of performance…");
  });

  it("marks AI-generated points", async () => {
    respond(200, { points, source: "ai" });
    const user = setup();
    await user.click(toggle());
    expect(await screen.findByText(/Generated by AI/)).toBeInTheDocument();
  });

  it("hides the panel when closed and doesn't reload when reopened", async () => {
    respond(200, { points, source: "curated" });
    const user = setup();
    await user.click(toggle());
    const cue = await screen.findByText("Front rack with elbows high");

    await user.click(toggle());
    expect(cue).not.toBeVisible();

    await user.click(toggle());
    expect(cue).toBeVisible();
    expect(fetchMock).toHaveBeenCalledTimes(1);
  });

  it("shows errors with a retry button", async () => {
    respond(500, { error: "Rate limited. Try again in a moment." });
    const user = setup();
    await user.click(toggle());
    expect(await screen.findByRole("alert")).toHaveTextContent("Rate limited.");

    respond(200, { points, source: "ai" });
    await user.click(screen.getByRole("button", { name: "Retry" }));
    expect(await screen.findByText("Front rack with elbows high")).toBeInTheDocument();
  });
});
